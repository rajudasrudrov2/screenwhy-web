import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read=(f)=>readFileSync(f,'utf8');
const component=read('src/components/domain/quick-answer/QuickAnswer.tsx');
const detail=read('src/features/explanation-detail/ExplanationDetail.tsx');
const styles=read('src/components/domain/quick-answer/QuickAnswer.module.css');
const backendContract=read('src/types/domain/explanation.ts');
let passes=0;
const test=(condition,label)=>{assert.ok(condition,label);console.log('PASS '+label);passes++;};
test(detail.includes('label="Cut to the Chase"'), 'Explanation label is Cut to the Chase');
test(detail.includes('sectionId="cut-to-the-chase"'), 'stable anchor ID on explanation');
test(detail.includes('prominentHeading'), 'Explanation uses second-level accessible heading');
test(detail.includes('protectSpoilers'), 'spoiler protection explicitly enabled');
test((detail.match(/<QuickAnswer/g)||[]).length===1, 'exactly one explanation quick-answer component');
test(component.includes('SpoilerDisclosure') && component.includes('spoiler.screen.level === "major"') && component.includes('spoiler.screen.level === "full"'), 'major/full answer requires disclosure');
test(component.includes('paragraphs.length === 0) return null'), 'empty text does not invent editorial prose');
test(component.includes('aria-labelledby={headingId}'), 'accessible section heading association');
test(styles.includes('scroll-margin-top') && styles.includes('overflow-wrap'), 'focus target and overflow protection');
test(backendContract.includes('readonly quickAnswer: string'), 'existing REST-mapped model field remains unchanged');
test(!detail.includes('cut_to_the_chase') && !component.includes('cut_to_the_chase'), 'no duplicate answer property');
console.log(`SW_EXT_01B_ASSERTIONS_PASS=${passes}`);
